import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const guideCount = JSON.parse(await readFile(new URL('../docs/learning/catalog.json', import.meta.url), 'utf8')).guides.length;

export async function testLearning(browser, base) {
  const context = await browser.newContext({viewport: {width: 1280, height: 900}, acceptDownloads: true});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(`${base}learn/index.html#vector-frames`);
    assert.equal(await page.locator('h2:visible').textContent(), 'Frame-by-frame drawing');
    const nav = page.getByRole('navigation', {name: 'Lessons'});
    assert.equal(await nav.locator('a').count(), guideCount);
    await page.getByLabel('Find a lesson').fill('onion');
    assert.equal(await nav.locator('a:visible').count(), 1);
    await page.getByLabel('Find a lesson').fill('unmatched tutorial');
    assert.equal(await page.locator('#results').textContent(), '0 lessons found');
    await page.getByLabel('Find a lesson').fill('');
    await page.getByRole('button', {name:'Next step', exact:true}).click();
    assert.match(await page.locator('.step').textContent(), /Draw on the current frame/);
    await page.reload();
    assert.match(await page.locator('.step').textContent(), /Draw on the current frame/);
    await page.getByRole('button', {name:'Restart lesson'}).click();
    assert.match(await page.locator('.step').textContent(), /Open Frames/);
    await page.getByLabel('Onion skin').check();
    assert.equal(await page.locator('.demo svg circle').count(), 2);
    await page.getByRole('button', {name:'2: B', exact:true}).click();
    assert.equal(await page.locator('.demo svg circle').count(), 3);
    await page.getByRole('button', {name:'Play', exact:true}).click();
    await page.waitForFunction(() => document.querySelector('.demo svg').getAttribute('aria-label') !== 'Drawing 2, exposure 2');
    await page.getByRole('button', {name:'Pause', exact:true}).click();
    await nav.getByText('Shape motion in the graph', {exact:true}).click();
    await page.getByLabel('Easing').selectOption('Hold');
    assert.match(await page.locator('.demo:visible svg').getAttribute('aria-label'), /0% distance/);
    await nav.getByText('Draw and animate gradients', {exact:true}).click();
    await page.getByLabel('Gradient direction').fill('180');
    assert.match(await page.locator('.demo:visible svg').getAttribute('aria-label'), /180 degrees/);
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('link', {name:'Download PDF'}).click();
    const download = await downloadEvent;
    assert.equal(download.suggestedFilename(), 'Arcflow-Tutorials.pdf');
    const stream = await download.createReadStream();
    const chunks = []; for await (const chunk of stream) chunks.push(chunk);
    const pdf = Buffer.concat(chunks);
    assert.equal(pdf.subarray(0,5).toString(), '%PDF-');
    assert.ok(pdf.length > 20000);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path:'/tmp/arcflow-learning-mobile.png',fullPage:true});
    await page.setViewportSize({width:1440,height:900});
    await nav.getByText('Frame-by-frame drawing',{exact:true}).click();
    await page.screenshot({path:'/tmp/arcflow-learning.png',fullPage:true});
    await page.getByRole('link', {name:'Practice in editor'}).click();
    await page.waitForFunction(() => globalThis.Module?.afCanvasFrames > 3, null, {timeout:60000});
    assert.ok(await page.evaluate(() => Module.arguments.includes('--tutorial') && Module.arguments.includes('vector-frames')));
    await page.screenshot({path:'/tmp/arcflow-learning-editor.png'});
    // Walkthrough must leave editor tools usable, not swallow all keys like a modal.
    await page.keyboard.press('Shift+F6');
    await page.keyboard.press('r');
    await page.mouse.move(410,410); await page.mouse.down(); await page.mouse.move(510,490,{steps:5}); await page.mouse.up();
    page.on('dialog', d => d.type() === 'prompt' ? d.accept('tutorial.afproj') : d.accept());
    const saved = page.waitForEvent('download');
    await page.keyboard.press('Control+s');
    const filename = (await saved).suggestedFilename();
    assert.match(filename, /\.afproj$/);
    const source = await page.evaluate(name => Module.FS.readFile('/documents/' + name, {encoding:'utf8'}), filename);
    const nodes = (source.match(/^node$/gm) || []).length;
    assert.ok(nodes > 3, 'Walkthrough allows a new drawing in the current project');
    await page.evaluate(() => new Promise((resolve, reject) => Module.FS.syncfs(false, e => e ? reject(e) : resolve())));
    await page.goto(`${base}?tutorial=gradients`);
    await page.waitForFunction(() => globalThis.Module?.afCanvasFrames > 3, null, {timeout:60000});
    assert.ok(await page.evaluate(name => Module.arguments.includes('/documents/' + name), filename));
    const resave = page.waitForEvent('download');
    await page.keyboard.press('Control+s');
    await resave;
    const restored = await page.evaluate(name => Module.FS.readFile('/documents/' + name, {encoding:'utf8'}), filename);
    assert.equal((restored.match(/^node$/gm) || []).length, nodes, 'Changing tutorials preserves drawings');
    assert.deepEqual(errors, []);
  } finally { await context.close(); }
  const blocked = await browser.newContext();
  await blocked.addInitScript(() => { Storage.prototype.getItem = Storage.prototype.setItem = () => {throw new Error('disabled storage');}; });
  const fallback = await blocked.newPage();
  await fallback.goto(`${base}learn/index.html#quick-start`);
  await fallback.getByRole('button', {name:'Next step',exact:true}).click();
  assert.match(await fallback.locator('.step').textContent(), /Select the shape/);
  await blocked.close();
  const nojs = await browser.newContext({javaScriptEnabled:false});
  const printable = await nojs.newPage();
  await printable.goto(`${base}learn/print.html`);
  assert.equal(await printable.locator('article').count(),guideCount);
  await nojs.close();
  console.log('PASS learning: search, progress, demos, PDF, mobile, editor walkthrough, storage fallback, offline content');
}
