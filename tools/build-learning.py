#!/usr/bin/env python3
"""Generate editor guides and offline learning pages from one validated catalog."""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parent.parent
MAX_STEPS = 8


def load_catalog(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    if set(data) != {"schema_version", "guides"} or data["schema_version"] != 1:
        raise ValueError("Expected catalog schema_version 1 and guides")
    if not isinstance(data["guides"], list) or not data["guides"]:
        raise ValueError("Catalog needs guides")
    ids, slugs = set(), set()
    for guide in data["guides"]:
        required = {"id", "slug", "title", "summary", "category", "minutes", "steps"}
        if not required <= guide.keys() or guide.keys() - required - {"demo"}:
            raise ValueError("Unknown or missing guide field")
        for field, limit in (("id", 80), ("slug", 64), ("title", 64), ("summary", 200), ("category", 30)):
            if not isinstance(guide[field], str) or not 0 < len(guide[field]) <= limit:
                raise ValueError(f"Invalid {field}")
        if not re.fullmatch(r"AF_ONBOARDING_[A-Z_]+", guide["id"]) or guide["id"] == "AF_ONBOARDING_TOPIC_COUNT":
            raise ValueError("Invalid C topic id")
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", guide["slug"]):
            raise ValueError("Invalid slug")
        if guide["id"] in ids or guide["slug"] in slugs:
            raise ValueError("Duplicate guide id or slug")
        ids.add(guide["id"])
        slugs.add(guide["slug"])
        if type(guide["minutes"]) is not int or not 1 <= guide["minutes"] <= 60:
            raise ValueError("Invalid reading time")
        if guide.get("demo", "") not in ("", "frames", "curves", "gradient"):
            raise ValueError("Unknown interactive demo")
        if not isinstance(guide["steps"], list) or not 1 <= len(guide["steps"]) <= MAX_STEPS:
            raise ValueError("Invalid step count")
        for step in guide["steps"]:
            if "text" not in step or step.keys() - {"text", "detail"}:
                raise ValueError("Unknown or missing step field")
            for field, limit in (("text", 200), ("detail", 250)):
                value = step.get(field, "")
                if not isinstance(value, str) or len(value) > limit or (field == "text" and not value.strip()):
                    raise ValueError(f"Invalid step {field}")
                if any(ord(c) < 32 for c in value):
                    raise ValueError("Control characters are not supported")
    return data


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:12]


def generate(catalog, generated, site, version):
    guides = catalog["guides"]
    revision = fingerprint(catalog)
    generated.mkdir(parents=True, exist_ok=True)
    site.mkdir(parents=True, exist_ok=True)
    enums = "\n".join("    " + g["id"] + "," for g in guides)
    (generated / "onboarding_topics.h").write_text(
        "/* Generated by tools/build-learning.py; edit docs/learning/catalog.json. */\n"
        "#ifndef AF_ONBOARDING_TOPICS_H\n#define AF_ONBOARDING_TOPICS_H\n"
        f"#define AF_ONBOARDING_MAX_STEPS {MAX_STEPS}U\n"
        f"typedef enum AfOnboardingTopic {{\n{enums}\n    AF_ONBOARDING_TOPIC_COUNT\n}} AfOnboardingTopic;\n#endif\n", encoding="utf-8")
    lines = ["/* Generated; edit docs/learning/catalog.json. */",
             "static const AfOnboardingGuide af_onboarding_guides[AF_ONBOARDING_TOPIC_COUNT] = {"]
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    for g in guides:
        lines.append(f'    [{g["id"]}] = {{')
        for field in ("slug", "title", "summary"):
            lines.append(f'        .{field} = {quote(g[field])},')
        for field, source in (("steps", "text"), ("details", "detail")):
            lines.append(f'        .{field} = {{' + ", ".join(quote(s.get(source, "")) for s in g["steps"]) + "},")
        lines.append(f'        .step_count = {len(g["steps"])}U}},')
    lines.append("};\n")
    (generated / "onboarding_guides.inc").write_text("\n".join(lines), encoding="utf-8")
    esc = html.escape
    stamp = f"Arcflow {version} · Lessons {revision}"
    articles = []
    for g in guides:
        steps = "".join(f'<li><h3>{esc(s["text"])}</h3><p>{esc(s.get("detail", ""))}</p></li>' for s in g["steps"])
        articles.append(f'<article id="{g["slug"]}" data-revision="{fingerprint(g)}"><p class="eyebrow">{esc(g["category"])} · {g["minutes"]} min</p><h2>{esc(g["title"])}</h2><p class="summary">{esc(g["summary"])}</p><ol>{steps}</ol></article>')
    head = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Arcflow — Learn</title><link rel="stylesheet" href="learn.css"><body>'
    nav = "".join(f'<a href="#{g["slug"]}" data-guide="{g["slug"]}">{esc(g["title"])}</a>' for g in guides)
    content = "\n".join(articles)
    (site / "print.html").write_text(head + f'<header><p class="eyebrow">ARCFLOW / FIELD GUIDE</p><h1>Make something move.</h1><p>{esc(stamp)}</p><p>Practical tutorials and reference. Default shortcuts are shown; Help &gt; Keyboard Shortcuts lists your bindings.</p><div class="actions"><button onclick="window.print()">Print / Save PDF</button><a href="index.html">Interactive lessons</a></div><nav class="contents">{nav}</nav></header><main>{content}</main></body></html>', encoding="utf-8")
    payload = json.dumps(catalog, ensure_ascii=False).replace("<", "\\u003c")
    (site / "index.html").write_text(head + f'''
<a class="skip" href="#lesson">Skip to lesson</a>
<header><p class="eyebrow">ARCFLOW / LEARN</p><h1>Make something move.</h1><p>Short lessons. Hands-on examples. Your next animation.</p>
<div class="actions"><a href="../">Open editor</a><a id="pdf" href="Arcflow-Tutorials.pdf" download>Download PDF</a><a href="print.html">Printable guide</a></div><small>{esc(stamp)}</small></header>
<div class="layout"><aside><label for="search">Find a lesson</label><input id="search" type="search" placeholder="Try frames or gradients"><p id="results" role="status"></p><nav aria-label="Lessons">{nav}</nav></aside>
<main id="lesson" tabindex="-1">{content}</main></div>
<footer>Default shortcuts shown. Check Help → Keyboard Shortcuts for your bindings. Progress stays in this browser.</footer>
<script id="catalog" type="application/json">{payload}</script><script src="learn.js" defer></script></body></html>''', encoding="utf-8")
    for name in ("learn.css", "learn.js"):
        shutil.copyfile(ROOT / "docs/learning" / name, site / name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=ROOT / "docs/learning/catalog.json")
    parser.add_argument("--generated", type=Path)
    parser.add_argument("--site", type=Path)
    parser.add_argument("--version", default="development")
    args = parser.parse_args()
    catalog = load_catalog(args.catalog)
    if args.generated and args.site:
        generate(catalog, args.generated, args.site, args.version)
    elif args.generated or args.site:
        parser.error("--generated and --site must be used together")
    print(f"Validated {len(catalog['guides'])} guides ({fingerprint(catalog)})")


if __name__ == "__main__":
    main()
